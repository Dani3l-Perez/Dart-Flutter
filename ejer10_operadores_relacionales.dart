// Programa que demuestra el uso de operadores relacionales en Dart.

void main() {
  // Declaramos dos variables numéricas
  int x = 8;
  int y = 12;

  // Operadores relacionales
  print("x == y : ${x == y}");   // ¿x es igual a y?
  print("x != y : ${x != y}");   // ¿x es diferente de y?
  print("x < y  : ${x < y}");    // ¿x es menor que y?
  print("x > y  : ${x > y}");    // ¿x es mayor que y?
  print("x <= y : ${x <= y}");   // ¿x es menor o igual que y?
  print("x >= y : ${x >= y}");   // ¿x es mayor o igual que y?
}
