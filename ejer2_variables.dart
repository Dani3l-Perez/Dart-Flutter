// Declaración de variables en Dart:
// - Se utiliza la palabra reservada "String" para declarar variables de tipo cadena de texto.
// - También podemos declarar variables de otros tipos, como "int", "double", etc.

void main() {
  // Variable de tipo String que almacena un nombre
  String nombre = "Daniel";

  // Variable de tipo int que almacena una edad
  int edad = 22;

  // "print()" se usa para mostrar el valor de cada variable en consola
  print("Nombre: $nombre");
  print("Edad: $edad");
}
