// El programa comienza en la función main(), declarada con la palabra reservada "void".
// En este caso, vamos a trabajar con variables de tipo "double" y "String".

void main() {
  // Declaramos una variable de tipo double para representar una altura en metros
  double altura = 1.75;

  // Declaramos una variable de tipo String para representar una cita favorita
  String citaFavorita = "El éxito es la suma de pequeños esfuerzos repetidos cada día.";

  // Mostramos en consola los valores usando la función print()
  print("Mi altura es: $altura metros");
  print("Mi cita favorita es: $citaFavorita");
}
