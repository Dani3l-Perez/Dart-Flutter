// Programa que demuestra el uso de operadores aritméticos en Dart.

void main() {
  // Declaramos dos variables enteras
  int a = 10;
  int b = 3;

  // Operaciones aritméticas
  print("a + b = ${a + b}");   // Suma
  print("a - b = ${a - b}");   // Resta
  print("a * b = ${a * b}");   // Multiplicación
  print("a / b = ${a / b}");   // División con decimales
  print("a ~/ b = ${a ~/ b}"); // División entera (sin decimales)
  print("a % b = ${a % b}");   // Módulo (residuo)
}
